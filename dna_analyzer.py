def is_valid(seq):
    """Return True if the sequence contains only A, T, G, C."""
    return len(seq) > 0 and all(base in "ATGC" for base in seq)


def count_bases(seq):
    """Count how many times each base appears."""
    counts = {"A": 0, "T": 0, "G": 0, "C": 0}
    for base in seq:
        counts[base] += 1
    return counts


def gc_content(seq):
    """Return GC content as a percentage."""
    return (seq.count("G") + seq.count("C")) / len(seq) * 100


def reverse_complement(seq):
    """Return the reverse complement of the sequence."""
    pairs = {"A": "T", "T": "A", "G": "C", "C": "G"}
    return "".join(pairs[base] for base in reversed(seq))


def translate(seq):
    """Translate DNA into a protein, stopping at the first stop codon."""
    protein = ""
    for i in range(0, len(seq) - 2, 3):
        amino_acid = CODON_TABLE[seq[i:i + 3]]
        if amino_acid == "*":
            break
        protein += amino_acid
    return protein


def main():
    seq = input("Enter a DNA sequence (A, T, G, C only): ").strip().upper()

    if not is_valid(seq):
        print("Invalid sequence. Use only the letters A, T, G and C.")
        return

    counts = count_bases(seq)
    print(f"\nLength: {len(seq)} bases")
    print(f"Base counts: A={counts['A']}, T={counts['T']}, G={counts['G']}, C={counts['C']}")
    print(f"GC content: {gc_content(seq):.1f}%")
    print(f"Reverse complement: {reverse_complement(seq)}")
    print(f"Protein (translated): {translate(seq)}")


main()
